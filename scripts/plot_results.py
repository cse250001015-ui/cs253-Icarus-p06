#!/usr/bin/env python3
"""Plot percolation scaling and union-find benchmark CSVs with Matplotlib.

Run from any directory with:
  python scripts/plot_results.py

The default scaling input is results/raw/summary.csv. To plot another run, pass
--scaling-csv results/raw/<run-folder>/summary.csv. Benchmark plots use
results/raw/percolation_sweep_summary.csv by default.
"""

import argparse
import csv
import math
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


ROOT = Path(__file__).resolve().parents[1]
PUBLISHED_PC = 0.592746
VARIANT_ORDER = ("naive", "rank", "compress", "rank_compress")
VARIANT_LABELS = {
    "naive": "Naive linking",
    "rank": "Union by rank",
    "compress": "Path compression",
    "rank_compress": "Rank + compression",
}


def read_csv(path):
    if not path.is_file():
        raise FileNotFoundError(f"CSV not found: {path}")
    with path.open(newline="", encoding="utf-8-sig") as stream:
        rows = list(csv.DictReader(stream))
    if not rows:
        raise ValueError(f"CSV has no data rows: {path}")
    return rows


def ordinary_least_squares(x_values, y_values):
    """Return intercept, slope, and the residual-based standard error of intercept."""
    count = len(x_values)
    if count < 2:
        return None
    sx = sum(x_values)
    sy = sum(y_values)
    sxx = sum(x * x for x in x_values)
    sxy = sum(x * y for x, y in zip(x_values, y_values))
    delta = count * sxx - sx * sx
    if abs(delta) <= 1e-300:
        return None
    slope = (count * sxy - sx * sy) / delta
    intercept = (sxx * sy - sx * sxy) / delta
    if count <= 2:
        intercept_se = float("nan")
    else:
        residual_sum = sum((y - (intercept + slope * x)) ** 2
                           for x, y in zip(x_values, y_values))
        residual_variance = residual_sum / (count - 2)
        intercept_se = math.sqrt(max(0.0, residual_variance * sxx / delta))
    return intercept, slope, intercept_se


def t_label(rows):
    values = {row.get("T", "") for row in rows if row.get("T", "")}
    return next(iter(values)) if len(values) == 1 else "varied"


def plot_scaling_ols(csv_path, output_dir):
    rows = read_csv(csv_path)
    required = {"variant", "L", "mean_p", "se"}
    if not required.issubset(rows[0]):
        raise ValueError(f"{csv_path} must contain columns: {', '.join(sorted(required))}")
    grouped = defaultdict(list)
    for row in rows:
        L = float(row["L"])
        grouped[row["variant"]].append((L ** -0.75, float(row["mean_p"]), float(row["se"])))

    fig, ax = plt.subplots(figsize=(8.5, 5.8))
    colors = plt.get_cmap("tab10")
    annotated_sizes = set()
    for i, variant in enumerate(VARIANT_ORDER):
        points = sorted(grouped.get(variant, []))
        if not points:
            continue
        x = [p[0] for p in points]
        y = [p[1] for p in points]
        se = [p[2] for p in points]
        color = colors(i)
        ax.errorbar(x, y, yerr=se, fmt="o", capsize=3, color=color,
                    label=f"{VARIANT_LABELS.get(variant, variant)} simulation mean $\\pm$ SE")
        for x_value, y_value in zip(x, y):
            size = int(round(x_value ** (-4.0 / 3.0)))
            if size not in annotated_sizes:
                ax.annotate(f"L={size}", (x_value, y_value), xytext=(5, 7),
                            textcoords="offset points", fontsize=8, color=color)
                annotated_sizes.add(size)
        fit = ordinary_least_squares(x, y)
        if fit is not None:
            intercept, slope, intercept_se = fit
            x_line = [0.0, max(x) * 1.04]
            y_line = [intercept + slope * value for value in x_line]
            fit_label = f"{VARIANT_LABELS.get(variant, variant)} OLS: $p_c(\\infty)$={intercept:.6f}"
            if math.isfinite(intercept_se):
                fit_label += f" $\\pm$ {intercept_se:.6f}"
            if variant == "rank_compress":
                ax.plot(x_line, y_line, color=color, linewidth=2, label=fit_label)
            else:
                # Keep each variant's fitted p_c in the legend without drawing its fit line.
                ax.plot([], [], color=color, linewidth=2, label=fit_label)

    ax.axhline(PUBLISHED_PC, color="red", linestyle="--", linewidth=1.3,
               label=f"Theoretical reference $p_c$={PUBLISHED_PC}")
    ax.set_xlabel(r"$L^{-1/\nu}=L^{-0.75}$, with $\nu=4/3$")
    ax.set_ylabel(r"Estimated percolation threshold $p_c(L)$")
    ax.set_title(f"Finite-size scaling OLS regression (T={t_label(rows)})")
    ax.grid(True, linestyle=":", alpha=0.45)
    ax.legend(fontsize=8)
    fig.text(0.01, 0.01,
             f"Source: {csv_path.relative_to(ROOT) if csv_path.is_relative_to(ROOT) else csv_path}; "
             "error bars show one SE. Generated by scripts/plot_results.py.", fontsize=8)
    fig.tight_layout(rect=(0, 0.06, 1, 1))
    output = output_dir / "finite_size_scaling_ols.png"
    fig.savefig(output, dpi=180)
    plt.close(fig)
    return output


def plot_benchmark(csv_path, output_dir, metric, ylabel, filename, scale_factor=1.0):
    rows = read_csv(csv_path)
    required = {"variant", "L", f"mean_{metric}", f"sd_{metric}"}
    if not required.issubset(rows[0]):
        raise ValueError(f"{csv_path} must contain columns: {', '.join(sorted(required))}")

    grouped = defaultdict(list)
    for row in rows:
        grouped[row["variant"]].append((
            int(row["L"]),
            float(row[f"mean_{metric}"]) / scale_factor,
            float(row[f"sd_{metric}"]) / scale_factor,
        ))

    fig, ax = plt.subplots(figsize=(8.5, 5.8))
    colors = plt.get_cmap("tab10")
    plotted = False
    for i, variant in enumerate(VARIANT_ORDER):
        points = sorted(grouped.get(variant, []))
        if not points:
            continue
        plotted = True
        ax.errorbar([p[0] for p in points], [p[1] for p in points],
                    yerr=[p[2] for p in points], marker="o", capsize=3,
                    color=colors(i), label=VARIANT_LABELS.get(variant, variant))

    if not plotted:
        raise ValueError(f"No recognized variant rows in {csv_path}")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("Grid side $L$ (sites)")
    ax.set_ylabel(ylabel)
    ax.set_title("Percolation sweep cost by union-find variant")
    ax.grid(True, which="both", linestyle=":", alpha=0.45)
    ax.legend()
    fig.text(0.01, 0.01,
             f"Source: {csv_path.relative_to(ROOT) if csv_path.is_relative_to(ROOT) else csv_path}; "
             "points are means, error bars are one sample SD. Generated by scripts/plot_results.py.",
             fontsize=8)
    fig.tight_layout(rect=(0, 0.06, 1, 1))
    output = output_dir / filename
    fig.savefig(output, dpi=180)
    plt.close(fig)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scaling-csv", type=Path,
                        default=ROOT / "results/raw/summary.csv",
                        help="application summary.csv to plot")
    parser.add_argument("--benchmark-csv", type=Path,
                        default=ROOT / "results/raw/percolation_sweep_summary.csv",
                        help="benchmark summary CSV")
    parser.add_argument("--out-dir", type=Path, default=ROOT / "results/figures",
                        help="directory for generated PNG figures")
    args = parser.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    outputs = [plot_scaling_ols(args.scaling_csv, args.out_dir)]
    # benchmark mean_time_ns is converted to milliseconds for a readable axis
    outputs.append(plot_benchmark(args.benchmark_csv, args.out_dir, "time_ns",
                                  "Mean time per sweep (ms)",
                                  "percolation_sweep_time.png", scale_factor=1e6))
    outputs.append(plot_benchmark(args.benchmark_csv, args.out_dir, "hops",
                                  "Mean parent-pointer hops per sweep",
                                  "percolation_sweep_hops.png"))
    for path in outputs:
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
